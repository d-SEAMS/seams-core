"""Validate active towncrier fragments and their rendered order."""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys
import tempfile
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONFIG = ROOT / "towncrier.toml"
CHANGELOG = ROOT / "CHANGELOG.md"
NOTES = ROOT / "docs" / "source" / "reference" / "release-2.14-notes.rst"
PAGE = ROOT / "docs" / "orgmode" / "reference" / "release-2.14.org"
MINIMUM_FRAGMENTS = 100
IGNORED = {"README.md", ".gitkeep"}
CODE = re.compile(r"`([^`]+)`")
RELEASE = re.compile(r"^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})$", re.M)


def read_config():
    data = tomllib.loads(CONFIG.read_text())
    towncrier = data.get("tool", {}).get("towncrier", {})
    directory = towncrier.get("directory")
    if not isinstance(directory, str) or not directory:
        raise ValueError("tool.towncrier.directory is missing")
    types = tuple(
        item.get("directory")
        for item in data.get("tool", {}).get("towncrier", {}).get("type", [])
        if isinstance(item.get("directory"), str)
    )
    if not types:
        raise ValueError("tool.towncrier.type is missing")
    prefix = towncrier.get("orphan_prefix")
    if not isinstance(prefix, str) or not prefix:
        raise ValueError("tool.towncrier.orphan_prefix is missing")
    headings = {
        item["directory"]: item.get("name", item["directory"].title())
        for item in data.get("tool", {}).get("towncrier", {}).get("type", [])
        if isinstance(item.get("directory"), str)
    }
    return ROOT / directory, types, prefix, headings


def load():
    """Return (errors, fragments) with fragments as (type, name, body)."""
    errors = []
    found = []
    if not FRAGMENTS.is_dir():
        return ["missing {}".format(FRAGMENTS.relative_to(ROOT))], []
    for path in sorted(FRAGMENTS.iterdir()):
        if not path.is_file() or path.name in IGNORED:
            continue
        if path.suffix != ".md":
            errors.append("{} is not a news fragment".format(path.name))
            continue
        match = NAME.fullmatch(path.name)
        if match is None:
            errors.append("{} does not match fragment naming rules".format(path.name))
            continue
        body = path.read_text().strip()
        if not body:
            errors.append("{} is empty".format(path.name))
            continue
        found.append((match.group(2), path.name, body))
    seen = {}
    for _typ, name, body in found:
        key = " ".join(body.split())
        if key in seen:
            errors.append("{} repeats {}".format(name, seen[key]))
        else:
            seen[key] = name
    return errors, found


def rst_body(body):
    """Markdown code spans become reStructuredText literals."""
    return CODE.sub(lambda match: "``{}``".format(match.group(1)), body)


def render(fragments):
    lines = [
        ".. Generated by docs/check_changelog.py from changelog.d.",
        ".. Edit the fragment, not this file.",
        "",
    ]
    by_type = {name: [] for name in TYPES}
    for typ, name, body in fragments:
        by_type[typ].append((name, body))
    for typ in TYPES:
        items = by_type[typ]
        if not items:
            continue
        title = HEADINGS[typ]
        lines.append(title)
        lines.append("-" * len(title))
        lines.append("")
        for _name, body in items:
            text = rst_body(body).splitlines()
            lines.append("- {}".format(text[0]))
            for extra in text[1:]:
                lines.append("  {}".format(extra))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def bullets(text):
    """Bodies of the top-level bullets, with literals restored."""
    found = []
    current = None

    def close():
        nonlocal current
        if current is None:
            return
        body = "\n".join(line for line in current if line != "").strip()
        if body:
            found.append(re.sub(r"``([^`]+)``", r"`\1`", body))
        current = None

    for line in text.splitlines():
        if line.startswith("..") or set(line) <= {"-"} or line.strip() == "":
            if line.strip() == "":
                close()
            continue
        if line.startswith("- "):
            close()
            current = [line[2:]]
            continue
        if current is not None and line.startswith("  "):
            current.append(line[2:])
            continue
        close()
    close()
    return found


def check(fragments, rendered):
    errors = []
    if len(fragments) < MINIMUM_FRAGMENTS:
        errors.append(
            "expected at least {} towncrier fragments, found {}".format(
                MINIMUM_FRAGMENTS, len(fragments)
            )
        )
    parsed = bullets(rendered)
    wanted = []
    for typ in TYPES:
        wanted.extend(body for kind, _name, body in fragments if kind == typ)
    if parsed != wanted:
        missing = [body for body in wanted if body not in parsed]
        extra = [body for body in parsed if body not in wanted]
        repeated = [body for body in wanted if parsed.count(body) != 1]
        for body in missing:
            errors.append("orphan fragment: {}".format(body.splitlines()[0][:80]))
        for body in extra:
            errors.append("note is not a fragment: {}".format(body.splitlines()[0][:80]))
        for body in repeated:
            if body not in missing:
                errors.append("duplicate note: {}".format(body.splitlines()[0][:80]))
        if not errors:
            errors.append("rendered notes do not match the fragments")
    page = PAGE.read_text()
    if NOTES.name not in page:
        errors.append("{} does not include {}".format(PAGE.name, NOTES.name))
    return errors


def towncrier_draft():
    """Render the configured draft that the tracked changelog must contain."""
    match = RELEASE.search(CHANGELOG.read_text(encoding="utf-8"))
    if match is None:
        return None, "CHANGELOG.md has no release heading"
    version, date = match.groups()
    done = subprocess.run(
        [
            sys.executable,
            "-m",
            "towncrier",
            "build",
            "--draft",
            "--version",
            version,
            "--date",
            date,
        ],
        cwd=str(ROOT),
        check=False,
        capture_output=True,
        text=True,
    )
    if done.returncode != 0:
        return None, (done.stdout + done.stderr).strip() or "towncrier draft failed"
    marker = done.stdout.find("## [{}]".format(version))
    if marker < 0:
        return None, "towncrier draft has no {} heading".format(version)
    return done.stdout[marker:].strip() + "\n", None


def draft_matches_changelog(draft):
    return draft.strip() in CHANGELOG.read_text(encoding="utf-8")


def main(argv):
    global FRAGMENTS, TYPES, HEADINGS, NAME
    if argv not in ([], ["--check"], ["--selftest"]):
        print(
            "usage: docs/check_changelog.py [--check|--selftest]",
            file=sys.stderr,
        )
        return 2
    try:
        FRAGMENTS, TYPES, orphan_prefix, HEADINGS = read_config()
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    NAME = re.compile(
        r"^(" + re.escape(orphan_prefix) + r"[A-Za-z0-9][A-Za-z0-9.-]*|[0-9]+)\.("
        + "|".join(TYPES)
        + r")\.md$"
    )
    errors, fragments = load()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    rendered = render(fragments)
    if "--check" in argv or "--selftest" in argv:
        with tempfile.TemporaryDirectory(prefix="seams-release-notes-") as directory:
            candidate = pathlib.Path(directory) / NOTES.name
            candidate.write_text(rendered, encoding="utf-8")
            checked_render = candidate.read_text(encoding="utf-8")
    else:
        checked_render = rendered
    errors = check(fragments, checked_render)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    draft, draft_error = towncrier_draft()
    if draft_error is not None:
        print(draft_error, file=sys.stderr)
        return 1
    if not draft_matches_changelog(draft):
        print(
            "CHANGELOG.md does not contain the towncrier draft from {}".format(
                FRAGMENTS.relative_to(ROOT)
            ),
            file=sys.stderr,
        )
        return 1
    if "--selftest" in argv:
        first_body = rst_body(fragments[0][2]).splitlines()[0]
        mutated_render = checked_render.replace(
            first_body, first_body + " mismatch", 1
        )
        if mutated_render == checked_render or not check(fragments, mutated_render):
            print("rendered-note mismatch selftest did not fail", file=sys.stderr)
            return 1
        draft_line = fragments[0][2].splitlines()[0]
        mutated_draft = draft.replace(draft_line, draft_line + " mismatch", 1)
        if mutated_draft == draft or draft_matches_changelog(mutated_draft):
            print("fragment mismatch selftest did not fail", file=sys.stderr)
            return 1
        print("changelog mismatch selftest ok")
        return 0
    if "--check" not in argv:
        NOTES.parent.mkdir(parents=True, exist_ok=True)
        NOTES.write_text(rendered, encoding="utf-8")
    print(
        "changelog fragments match {} active entries in {}".format(
            len(fragments), FRAGMENTS.relative_to(ROOT)
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
