"""Write tests/ring_oracle_cells.inc: oxygen sites of ice II and ice III.

The ring oracle test (tests/test_ring_oracle.cpp) checks the primitive
ring search against a brute-force enumerator on these cells. Each cell is
the GenIce2 unit cell, rewritten in the LAMMPS lower-triangular form
a = (lx, 0, 0), b = (xy, ly, 0), c = (xz, yz, lz) with every tilt at most
half the matching length, so seams_system_set_atoms takes it as box9.

Needs genice2 (pip install genice2); it is not part of the pixi
environment because the .inc file is committed.
"""

import subprocess
import sys

import numpy as np


def genice_oxygens(phase):
    out = subprocess.run(
        ["genice2", "--format", "exyz", phase],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    xyz, vec = [], {}
    for line in out.splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "O":
            xyz.append([float(v) for v in parts[1:4]])
        elif parts[0].startswith("Vector"):
            vec[int(parts[0][-1])] = [float(v) for v in parts[1:4]]
    cell = np.array([vec[1], vec[2], vec[3]])
    return np.array(xyz), cell


def reduce_lammps(cell):
    a, b, c = (cell[i].copy() for i in range(3))
    if abs(a[1]) > 1e-9 or abs(a[2]) > 1e-9 or abs(b[2]) > 1e-9:
        raise RuntimeError("cell is not lower triangular")
    for _ in range(8):
        c -= np.round(c[1] / b[1]) * b
        c -= np.round(c[0] / a[0]) * a
        b -= np.round(b[0] / a[0]) * a
    return np.array([a, b, c])


def wrap(xyz, cell):
    frac = xyz @ np.linalg.inv(cell)
    frac -= np.floor(frac)
    return frac @ cell


def emit(name, xyz, cell, comment):
    lines = [f"// {comment}"]
    lines.append(f"static const int k{name}N = {len(xyz)};")
    lines.append(
        f"static const double k{name}Box9[9] = {{0, 0, 0, {cell[0][0]:.10f}, "
        f"{cell[1][1]:.10f}, {cell[2][2]:.10f}, {cell[1][0]:.10f}, "
        f"{cell[2][0]:.10f}, {cell[2][1]:.10f}}};"
    )
    lines.append(f"static const double k{name}Xyz[][3] = {{")
    for p in xyz:
        lines.append(f"  {{{p[0]:.10f}, {p[1]:.10f}, {p[2]:.10f}}},")
    lines.append("};")
    return "\n".join(lines)


def main():
    blocks = [
        "// Generated by scripts/gen_ring_oracle_cells.py from GenIce2 unit cells.",
        "// Oxygen sites only; box9 is ox, oy, oz, lx, ly, lz, xy, xz, yz.",
    ]
    for name, phase, label in (("IceII", "2", "ice II"), ("IceIII", "3", "ice III")):
        xyz, cell = genice_oxygens(phase)
        cell = reduce_lammps(cell)
        blocks.append(emit(name, wrap(xyz, cell), cell, f"{label}, GenIce2 lattice {phase}"))
    sys.stdout.write("\n".join(blocks) + "\n")


if __name__ == "__main__":
    main()
